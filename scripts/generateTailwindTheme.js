// Embeds Tailwind's default theme into the package, so no files have to be read at runtime
// (reading from node_modules breaks when the package is bundled, e.g. in serverless functions).
const fs = require('fs');
const path = require('path');

const theme = fs.readFileSync(require.resolve('tailwindcss/theme.css'), 'utf8');
const output = path.join(__dirname, '../src/generated/tailwindTheme.ts');

fs.writeFileSync(
  output,
  `// Generated by scripts/generateTailwindTheme.js from "tailwindcss/theme.css". Do not edit manually.\n` +
    `export const TAILWIND_THEME_CSS: string = ${JSON.stringify(theme)};\n`,
);
